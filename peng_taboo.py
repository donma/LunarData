def get_peng_taboo_explain(taboo_text):
    """解析彭祖百忌並返回白話解釋"""
    if not taboo_text:
        return []
    
    results = []
    # 用逗號分割（一個完整的禁忌用逗號分隔）
    parts = taboo_text.split(',')
    
    for part in parts:
        part = part.strip()
        if not part:
            continue
        
        # 尋找匹配的解釋（嘗試多個關鍵詞）
        best_explain = ""
        best_key = ""
        
        for key, explain in PENG_TABOO_EXPLAIN.items():
            if key in part and len(key) > len(best_key):
                best_explain = explain
                best_key = key
        
        if best_explain:
            results.append({"original": part, "explain": best_explain})
        else:
            results.append({"original": part, "explain": ""})
    
    return results
