def get_solar_term_info(dt, solar_terms_dict):
    """取得當前所處節氣資訊"""
    sorted_terms = sorted(solar_terms_dict.items(), key=lambda x: (x[1][0], x[1][1]))

    current_term = None
    next_term = None

    for i, (name, (m, d)) in enumerate(sorted_terms):
        term_date = datetime.date(dt.year, m, d)
        if dt.date() >= term_date:
            current_term = (name, m, d)
            if i + 1 < len(sorted_terms):
                next_name, (next_m, next_d) = sorted_terms[i + 1]
                next_term = (next_name, next_m, next_d)
            else:
                next_name, (next_m, next_d) = sorted_terms[0]
                next_term = (next_name, next_m, next_d)
        else:
            if current_term is None:
                current_term = (sorted_terms[-1][0], sorted_terms[-1][1][0], sorted_terms[-1][1][1])
                next_term = (name, m, d)
            break

    if current_term is None:
        current_term = (sorted_terms[-1][0], sorted_terms[-1][1][0], sorted_terms[-1][1][1])
        next_term = (sorted_terms[0][0], sorted_terms[0][1][0], sorted_terms[0][1][1])

    return {
        "name": s2t(current_term[0]),
        "startDate": f"{dt.year}-{current_term[1]:02d}-{current_term[2]:02d}",
        "endDate": f"{dt.year}-{next_term[1]:02d}-{next_term[2]:02d}" if next_term[1] >= current_term[1] else f"{dt.year + 1}-{next_term[1]:02d}-{next_term[2]:02d}",
        "nextName": s2t(next_term[0]),
        "nextDate": f"{dt.year}-{next_term[1]:02d}-{next_term[2]:02d}" if next_term[1] >= current_term[1] else f"{dt.year + 1}-{next_term[1]:02d}-{next_term[2]:02d}"
    }


