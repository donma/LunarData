def get_clash_zodiac(clash_str):
    """從沖煞字串提取被沖的生肖
    格式: "X日沖Y" 或 "X日冲Y"，Y 是被沖的生肖
    """
    if not clash_str:
        return ""
    
    # 找到"沖"或"冲"的位置，取後面的生肖
    clash_idx = -1
    for i, c in enumerate(clash_str):
        if c in ('沖', '冲'):
            clash_idx = i
            break
    
    if clash_idx >= 0:
        # 取"沖"後面的部分
        after_clash = clash_str[clash_idx+1:]
        # 從後面找第一個生肖
        for z in ZODIAC:
            if z in after_clash:
                return z
        for z in ZODIAC_SIMPLIFIED:
            if z in after_clash:
                return zodiac_to_traditional(z)
    
    # 備用：找最後出現的生肖
    for z in reversed(ZODIAC):
        if z in clash_str:
            return z
    for z in reversed(ZODIAC_SIMPLIFIED):
        if z in clash_str:
            return zodiac_to_traditional(z)
    return clash_str


def parse_clash_direction(clash_str, day_branch=None):
    """根據日地支計算煞方位（傳統算法）
    子日煞南、丑日煞東、寅日煞北、卯日煞西
    辰日煞南、巳日煞東、午日煞北、未日煞西
    申日煞南、酉日煞東、戌日煞北、亥日煞西
    """
    # 優先使用日地支計算
    if day_branch:
        sha_map = {
            "子": "南方", "丑": "東方", "寅": "北方", "卯": "西方",
            "辰": "南方", "巳": "東方", "午": "北方", "未": "西方",
            "申": "南方", "酉": "東方", "戌": "北方", "亥": "西方"
        }
        return sha_map.get(day_branch, "")
    
    # 備用：從沖煞字串推斷
    if not clash_str:
        return ""
    zodiac = get_clash_zodiac(clash_str)
    direction_map = {
        "鼠": "南方", "牛": "東方", "虎": "北方", "兔": "西方",
        "龍": "南方", "蛇": "東方", "馬": "北方", "羊": "西方",
        "猴": "南方", "雞": "東方", "狗": "北方", "豬": "西方"
    }
    return direction_map.get(zodiac, "")


