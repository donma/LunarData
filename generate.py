def s2t(text):
    """簡體轉繁體"""
    if not text:
        return text
    if isinstance(text, list):
        return [s2t(item) for item in text]
    if isinstance(text, dict):
        return {s2t(k): s2t(v) for k, v in text.items()}
    if isinstance(text, str):
        return ''.join(_S2T.get(c, c) for c in text)
    return text


