def get_jianchu_yiji(officer_name):
    """取得建除十二神派宜忌"""
    data = JIANCHU_YIJI.get(officer_name, None)
    if data:
        return {
            "school": "建除十二神派",
            "yi": data["yi"],
            "ji": data["ji"],
            "desc": data["desc"]
        }
    return None

def get_star28_yiji(star_name):
    """取得天星擇日派宜忌（二十八宿）"""
    if not star_name:
        return None
    
    # 嘗試完整名稱匹配
    data = STAR28_YIJI.get(star_name, None)
    
    # 如果沒找到，嘗試用第一個字匹配
    if not data and len(star_name) > 0:
        first_char = star_name[0]
        for key, val in STAR28_YIJI.items():
            if key.startswith(first_char):
                data = val
                break
    
    if data:
        return {
            "school": "天星擇日派",
            "yi": data["yi"],
            "ji": data["ji"],
            "desc": data["desc"]
        }
    return None

def get_jiubai_yiji(nine_star_str):
    """取得紫白九星派宜忌（取中宮星）"""
    if not nine_star_str or len(nine_star_str) < 1:
        return None
    center_star = nine_star_str[0]  # 中宮是第一個數字
    data = JIUBAI_YIJI.get(center_star, None)
    if data:
        return {
            "school": "紫白九星派",
            "yi": data["yi"],
            "ji": data["ji_list"],
            "desc": data["desc"]
        }
    return None
